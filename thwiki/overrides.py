def roster_display_name(hero_id: int, name: str | None) -> str:
    """Public label for the index list. Unreleased heroes include （未開放）."""
    if not name:
        return str(hero_id)
    if hero_id in UNRELEASED_HERO_IDS:
        return f"{name}（未開放）"
    return name


